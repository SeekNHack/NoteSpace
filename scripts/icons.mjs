const out = {};
for (const [key, file] of Object.entries(names)) {
  const source = await readFile(
    new URL(`../node_modules/lucide-static/dist/esm/icons/${file}.mjs`, import.meta.url),
    'utf8',
  );
  const inner = /<svg[^>]*>([\s\S]*?)<\/svg>/
    .exec(source)[1]
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
  out[key] = inner;
}
await writeFile(
  new URL('../src/core/icons.ts', import.meta.url),
  `/* Generated by scripts/icons.mjs from Lucide (ISC License, https://lucide.dev). */\nexport const iconPaths = ${JSON.stringify(out, null, 2)} as const;\nexport type IconName = keyof typeof iconPaths;\n/** Inline 16px stroke icon that inherits currentColor. */\nexport const icon = (name: IconName, size = 16): string =>\n  \`<svg class="icon" aria-hidden="true" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${iconPaths[name]}</svg>\`;\n/** CSS mask URL for the same icon. */\nexport const iconUrl = (name: IconName): string =>\n  \`url("data:image/svg+xml,\${encodeURIComponent(\`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\${iconPaths[name]}</svg>\`)}")\`;\n`,
);
